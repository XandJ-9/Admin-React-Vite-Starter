export type LucideIconName = keyof typeof lucideIcons;

export function getLucideIcon(name?: string | null): LucideIcon | null {
  if (!name) {
    return null;
  }

  return lucideIcons[name as LucideIconName] ?? null;
}

export function getLucideIconNames(): string[] {
  return Object.keys(lucideIcons).sort();
}
